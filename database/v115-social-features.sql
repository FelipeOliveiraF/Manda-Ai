alter table public.room_messages
  add column if not exists reply_to_id bigint,
  add column if not exists pinned_at timestamptz,
  add column if not exists pinned_by uuid;

do $$
begin
  if not exists (
    select 1 from pg_constraint
    where conname = 'room_messages_reply_to_id_fkey'
      and conrelid = 'public.room_messages'::regclass
  ) then
    alter table public.room_messages
      add constraint room_messages_reply_to_id_fkey
      foreign key (reply_to_id) references public.room_messages(id) on delete set null;
  end if;
  if not exists (
    select 1 from pg_constraint
    where conname = 'room_messages_pinned_by_fkey'
      and conrelid = 'public.room_messages'::regclass
  ) then
    alter table public.room_messages
      add constraint room_messages_pinned_by_fkey
      foreign key (pinned_by) references public.profiles(id) on delete set null;
  end if;
end $$;

create index if not exists room_messages_reply_to_id_idx
  on public.room_messages (reply_to_id) where reply_to_id is not null;
create index if not exists room_messages_channel_pinned_idx
  on public.room_messages (channel_id, pinned_at desc) where pinned_at is not null;
create index if not exists room_messages_pinned_by_idx
  on public.room_messages (pinned_by) where pinned_by is not null;

create table if not exists public.room_message_reactions (
  id bigint generated by default as identity primary key,
  room_id uuid not null references public.rooms(id) on delete cascade,
  channel_id bigint not null,
  message_id bigint not null references public.room_messages(id) on delete cascade,
  user_id uuid not null references public.profiles(id) on delete cascade,
  emoji text not null,
  created_at timestamptz not null default now(),
  constraint room_message_reactions_emoji_check check (char_length(emoji) between 1 and 16),
  constraint room_message_reactions_unique unique (message_id, user_id, emoji),
  constraint room_message_reactions_room_channel_fkey
    foreign key (room_id, channel_id) references public.room_channels(room_id, id) on delete cascade
);

create index if not exists room_message_reactions_room_channel_idx
  on public.room_message_reactions (room_id, channel_id, message_id);
create index if not exists room_message_reactions_user_id_idx
  on public.room_message_reactions (user_id);

alter table public.room_message_reactions enable row level security;

drop policy if exists room_message_reactions_read_members on public.room_message_reactions;
create policy room_message_reactions_read_members
on public.room_message_reactions for select
to authenticated
using ((select private.is_room_member(room_id)));

drop policy if exists room_message_reactions_insert_self on public.room_message_reactions;
create policy room_message_reactions_insert_self
on public.room_message_reactions for insert
to authenticated
with check (
  user_id = (select auth.uid())
  and (select private.is_room_member(room_id))
  and exists (
    select 1 from public.room_messages m
    where m.id = message_id
      and m.room_id = room_message_reactions.room_id
      and m.channel_id = room_message_reactions.channel_id
  )
);

drop policy if exists room_message_reactions_delete_self_or_admin on public.room_message_reactions;
create policy room_message_reactions_delete_self_or_admin
on public.room_message_reactions for delete
to authenticated
using (
  user_id = (select auth.uid())
  or (select private.is_room_admin(room_id))
);

drop policy if exists room_messages_insert_members on public.room_messages;
create policy room_messages_insert_members
on public.room_messages for insert
to authenticated
with check (
  user_id = (select auth.uid())
  and (select private.is_room_member(room_id))
  and exists (
    select 1 from public.room_channels c
    where c.id = room_messages.channel_id
      and c.room_id = room_messages.room_id
  )
  and (
    reply_to_id is null
    or exists (
      select 1 from public.room_messages parent
      where parent.id = room_messages.reply_to_id
        and parent.room_id = room_messages.room_id
        and parent.channel_id = room_messages.channel_id
    )
  )
);

create or replace function public.set_message_pinned(p_message_id bigint, p_pinned boolean)
returns public.room_messages
language plpgsql
security definer
set search_path = ''
as $$
declare
  target_room_id uuid;
  updated_message public.room_messages;
begin
  select room_id into target_room_id
  from public.room_messages
  where id = p_message_id;

  if target_room_id is null or not private.is_room_admin(target_room_id) then
    raise exception 'room administrator required';
  end if;

  update public.room_messages
  set pinned_at = case when p_pinned then now() else null end,
      pinned_by = case when p_pinned then (select auth.uid()) else null end
  where id = p_message_id
  returning * into updated_message;

  return updated_message;
end;
$$;

create or replace function public.create_room_invite_with_expiry(
  p_room_id uuid,
  p_expires_in_hours integer default null
)
returns table(token text, invite_id uuid, expires_at timestamptz)
language plpgsql
security definer
set search_path = ''
as $$
declare
  current_user_id uuid := (select auth.uid());
  raw_token text;
  created_invite_id uuid;
  calculated_expiry timestamptz;
begin
  if current_user_id is null or not private.is_room_member(p_room_id) then
    raise exception 'room membership required';
  end if;
  if p_expires_in_hours is not null and p_expires_in_hours not between 1 and 720 then
    raise exception 'expiry must be between 1 and 720 hours';
  end if;

  raw_token := encode(extensions.gen_random_bytes(24), 'hex');
  calculated_expiry := case when p_expires_in_hours is null then null else now() + make_interval(hours => p_expires_in_hours) end;

  insert into public.room_invites(room_id, token_hash, created_by, expires_at)
  values (p_room_id, encode(extensions.digest(raw_token, 'sha256'), 'hex'), current_user_id, calculated_expiry)
  returning id into created_invite_id;

  return query select raw_token, created_invite_id, calculated_expiry;
end;
$$;

create or replace function public.list_room_invites(p_room_id uuid)
returns table(
  id uuid,
  created_by uuid,
  creator_name text,
  expires_at timestamptz,
  revoked_at timestamptz,
  use_count integer,
  created_at timestamptz
)
language plpgsql
stable
security definer
set search_path = ''
as $$
begin
  if not private.is_room_admin(p_room_id) then
    raise exception 'room administrator required';
  end if;

  return query
  select i.id, i.created_by, p.display_name, i.expires_at, i.revoked_at, i.use_count, i.created_at
  from public.room_invites i
  join public.profiles p on p.id = i.created_by
  where i.room_id = p_room_id
  order by i.created_at desc
  limit 100;
end;
$$;

create or replace function public.revoke_room_invite(p_invite_id uuid)
returns void
language plpgsql
security definer
set search_path = ''
as $$
declare
  target_room_id uuid;
  invite_creator uuid;
begin
  select room_id, created_by into target_room_id, invite_creator
  from public.room_invites
  where id = p_invite_id;

  if target_room_id is null or (
    invite_creator <> (select auth.uid())
    and not private.is_room_admin(target_room_id)
  ) then
    raise exception 'invite manager required';
  end if;

  update public.room_invites
  set revoked_at = coalesce(revoked_at, now())
  where id = p_invite_id;
end;
$$;

revoke all on function public.set_message_pinned(bigint, boolean) from public, anon;
revoke all on function public.create_room_invite_with_expiry(uuid, integer) from public, anon;
revoke all on function public.list_room_invites(uuid) from public, anon;
