returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  if new.channel_id is null then
    select id into new.channel_id
    from public.room_channels
    where room_id = new.room_id
    order by position, id
    limit 1;
  end if;
  return new;
end;
$$;

