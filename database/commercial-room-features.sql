create or replace function public.set_room_member_role(p_room_id uuid, p_user_id uuid, p_role text)
returns public.room_members
language plpgsql
security definer
set search_path = ''
as $$
declare
  updated_member public.room_members;
begin
  if (select auth.uid()) is null or not private.is_room_owner(p_room_id) then
    raise exception 'room owner required';
  end if;
  if p_role not in ('admin', 'member') then
    raise exception 'invalid role';
  end if;
  if p_user_id = (select auth.uid()) then
    raise exception 'the owner role cannot be changed';
  end if;

  update public.room_members
  set role = p_role
  where room_id = p_room_id and user_id = p_user_id and role <> 'owner'
  returning * into updated_member;
  if updated_member.user_id is null then
    raise exception 'member not found';
  end if;
  return updated_member;
end;
$$;

create or replace function public.set_room_member_controls(
  p_room_id uuid,
  p_user_id uuid,
  p_is_muted boolean,
  p_can_share_screen boolean
)
returns public.room_members
language plpgsql
security definer
set search_path = ''
as $$
declare
  caller_role text;
  target_role text;
  updated_member public.room_members;
begin
  select role into caller_role
  from public.room_members
  where room_id = p_room_id and user_id = (select auth.uid());

  select role into target_role
  from public.room_members
  where room_id = p_room_id and user_id = p_user_id;

  if caller_role not in ('owner', 'admin') then
    raise exception 'room administrator required';
  end if;
  if target_role is null or target_role = 'owner' then
    raise exception 'this member cannot be moderated';
  end if;
  if target_role = 'admin' and caller_role <> 'owner' then
    raise exception 'only the owner can moderate an administrator';
  end if;

  update public.room_members
  set is_muted = p_is_muted,
      can_share_screen = p_can_share_screen
  where room_id = p_room_id and user_id = p_user_id
  returning * into updated_member;
  return updated_member;
end;
$$;

create or replace function public.remove_room_member(p_room_id uuid, p_user_id uuid)
returns void
language plpgsql
security definer
set search_path = ''
as $$
declare
  caller_role text;
  target_role text;
begin
  select role into caller_role
  from public.room_members
  where room_id = p_room_id and user_id = (select auth.uid());
  select role into target_role
  from public.room_members
  where room_id = p_room_id and user_id = p_user_id;

  if caller_role not in ('owner', 'admin') then
    raise exception 'room administrator required';
  end if;
  if target_role is null or target_role = 'owner' then
    raise exception 'this member cannot be removed';
  end if;
  if target_role = 'admin' and caller_role <> 'owner' then
    raise exception 'only the owner can remove an administrator';
  end if;

  delete from public.room_members where room_id = p_room_id and user_id = p_user_id;
end;
$$;

