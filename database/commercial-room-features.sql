create or replace function private.add_owner_membership()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  owner_name text;
begin
  select left(coalesce(nullif(trim(display_name), ''), 'Amigo'), 60)
  into owner_name
  from public.profiles
  where id = new.owner_id;

  insert into public.room_members (room_id, user_id, role, display_name)
  values (new.id, new.owner_id, 'owner', coalesce(owner_name, 'Amigo'))
  on conflict (room_id, user_id)
  do update set role = 'owner';

  insert into public.room_channels (room_id, name, position, created_by)
  values (new.id, 'geral', 0, new.owner_id)
  on conflict do nothing;

  return new;
end;
$$;

create or replace function public.accept_room_invite(p_token text)
returns table(room_id uuid)
language plpgsql
security definer
set search_path = ''
as $$
declare
  current_user_id uuid := (select auth.uid());
  found_invite public.room_invites;
  member_name text;
begin
  if current_user_id is null then
    raise exception 'authentication required';
  end if;

  select *
  into found_invite
  from public.room_invites
  where token_hash = encode(extensions.digest(trim(p_token), 'sha256'), 'hex')
    and revoked_at is null
    and (expires_at is null or expires_at > now())
  for update;

  if found_invite.id is null then
    raise exception 'invite not found or expired';
  end if;

  select left(coalesce(nullif(trim(display_name), ''), 'Amigo'), 60)
  into member_name
  from public.profiles
  where id = current_user_id;

  insert into public.room_members(room_id, user_id, role, display_name, last_joined_at)
  values (found_invite.room_id, current_user_id, 'member', coalesce(member_name, 'Amigo'), now())
  on conflict on constraint room_members_pkey
  do update set last_joined_at = excluded.last_joined_at;

  update public.room_invites
  set use_count = use_count + 1
  where id = found_invite.id;

  return query select found_invite.room_id;
end;
$$;

revoke all on function public.accept_room_invite(text) from public, anon;
grant execute on function public.accept_room_invite(text) to authenticated;

create or replace function public.update_room_nickname(p_room_id uuid, p_display_name text)
returns public.room_members
language plpgsql
security definer
set search_path = ''
as $$
declare
  current_user_id uuid := (select auth.uid());
  updated_member public.room_members;
  clean_name text := trim(p_display_name);
begin
  if current_user_id is null then
    raise exception 'authentication required';
  end if;
  if clean_name is null or char_length(clean_name) not between 1 and 60 then
    raise exception 'display name must contain 1 to 60 characters';
  end if;

  update public.room_members
  set display_name = clean_name
  where room_id = p_room_id and user_id = current_user_id
  returning * into updated_member;

  if updated_member.user_id is null then
    raise exception 'room membership required';
  end if;
  return updated_member;
end;
$$;

create or replace function public.create_room_channel(p_room_id uuid, p_name text)
returns public.room_channels
language plpgsql
security definer
set search_path = ''
as $$
declare
  current_user_id uuid := (select auth.uid());
  clean_name text := trim(p_name);
  created_channel public.room_channels;
begin
  if current_user_id is null or not private.is_room_admin(p_room_id) then
    raise exception 'room administrator required';
  end if;
  if clean_name is null or char_length(clean_name) not between 1 and 40 then
    raise exception 'channel name must contain 1 to 40 characters';
  end if;

  insert into public.room_channels (room_id, name, position, created_by)
  values (
    p_room_id,
    clean_name,
    coalesce((select max(position) + 1 from public.room_channels where room_id = p_room_id), 0),
    current_user_id
  )
  returning * into created_channel;
  return created_channel;
exception when unique_violation then
  raise exception 'a channel with this name already exists';
end;
$$;

create or replace function public.rename_room_channel(p_channel_id bigint, p_name text)
returns public.room_channels
language plpgsql
security definer
set search_path = ''
as $$
declare
  clean_name text := trim(p_name);
  target_room_id uuid;
  updated_channel public.room_channels;
begin
  select room_id into target_room_id from public.room_channels where id = p_channel_id;
  if target_room_id is null or not private.is_room_admin(target_room_id) then
    raise exception 'room administrator required';
  end if;
  if clean_name is null or char_length(clean_name) not between 1 and 40 then
    raise exception 'channel name must contain 1 to 40 characters';
  end if;

  update public.room_channels set name = clean_name where id = p_channel_id
  returning * into updated_channel;
  return updated_channel;
exception when unique_violation then
  raise exception 'a channel with this name already exists';
end;
$$;

create or replace function public.delete_room_channel(p_channel_id bigint)
returns void
language plpgsql
security definer
set search_path = ''
as $$
declare
  target_room_id uuid;
  channel_count integer;
begin
  select room_id into target_room_id from public.room_channels where id = p_channel_id;
  if target_room_id is null or not private.is_room_admin(target_room_id) then
    raise exception 'room administrator required';
  end if;

  select count(*) into channel_count from public.room_channels where room_id = target_room_id;
  if channel_count <= 1 then
    raise exception 'the last channel cannot be deleted';
  end if;
  delete from public.room_channels where id = p_channel_id;
end;
$$;

create or replace function public.clear_room_channel(p_channel_id bigint)
returns void
